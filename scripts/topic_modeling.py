def clean_token(token: str) -> str:
    """?????????????? ?????????????????? ?? ?????????????? (Unicode cantillation + vowels)."""
    # ?????????????????? Hebrew cantillation: U+0591???U+05C7, vowels U+05B0???U+05BD
    return re.sub(r'[\u0591-\u05C7\u05F0-\u05F4\u200d\u200e\u200f{}????]', '', token).strip()


def tokenize(text: str) -> list:
    """?????????????????????? ???????????????????? ???????????? ?? ??????????????????????."""
    tokens = text.split()
    result = []
    for tok in tokens:
        tok = clean_token(tok)
        if tok and tok not in HEBREW_STOPWORDS and len(tok) > 2:
            result.append(tok)
    return result


def label_topic(top_words: list) -> str:
    """???????????????????????????? ???????????????????? ???????? ???? ??????-????????????."""
    word_set = set(top_words)
    scores = {}
    for label, keywords in TOPIC_SIGNATURES.items():
        hit = len(word_set & set(keywords))
        if hit > 0:
            scores[label] = hit
    if scores:
        return max(scores, key=scores.get)
    return "other"


def run_lda(documents: list) -> dict:
    """?????????????????? LDA ?????????? sklearn, ???????????????????? ???????????? ??????."""
    if len(documents) < 5:
        return {"error": "not_enough_documents", "count": len(documents)}

    # Vectorizer: ???????????? gensim Dictionary + doc2bow
    vectorizer = CountVectorizer(
        analyzer=lambda text: tokenize(text) if isinstance(text, str) else text,
        min_df=2,
        max_df=0.95,
    )
    dtm = vectorizer.fit_transform(documents)
    vocab = vectorizer.get_feature_names_out()

    if dtm.shape[1] < NUM_TOPICS:
        actual_topics = max(2, dtm.shape[1] // 2)
    else:
        actual_topics = NUM_TOPICS

    lda = LatentDirichletAllocation(
        n_components=actual_topics,
        max_iter=LDA_PASSES,
        learning_method="batch",
        random_state=42,
    )
    lda.fit(dtm)

    topics = []
    for idx, component in enumerate(lda.components_):
        top_indices = component.argsort()[:-NUM_WORDS - 1:-1]
        top_words = [vocab[i] for i in top_indices]
        top_weights = [float(component[i]) for i in top_indices]
        label = label_topic(top_words)

        topics.append({
            "topic_id": idx,
            "label": label,
            "keywords": " + ".join(top_words),
            "top_words": top_words,
            "top_weights": top_weights,
        })

    # ?????????????????????????? ???????????????????? ???? ?????????? (???????? ???????????????????? ?? ???????????????????? ???? ???????????? ????????)
    doc_topic = lda.transform(dtm)
    topic_counts = defaultdict(int)
    for row in doc_topic:
        dominant = int(row.argmax())
        topic_counts[dominant] += 1

    total = len(documents)
    for t in topics:
        cnt = topic_counts.get(t["topic_id"], 0)
        t["doc_share_pct"] = round(cnt / total * 100, 1)

    return {
        "num_documents": len(documents),
        "num_topics": actual_topics,
        "topics": sorted(topics, key=lambda x: x["doc_share_pct"], reverse=True),
    }


def save_json(data: dict, path: str):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"  [OK] Saved: {path}")


